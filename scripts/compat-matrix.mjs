#!/usr/bin/env node
// Builds docs/compatibility.md from contract-results/*.json (written by `pnpm contract`).
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = 'contract-results';
if (!existsSync(dir)) {
  console.error('No contract-results/. Run `pnpm contract --spree <version>` first.');
  process.exit(1);
}
const runs = readdirSync(dir)
  .filter((f) => f.endsWith('.json'))
  .map((f) => JSON.parse(readFileSync(join(dir, f), 'utf8')))
  .sort((a, b) => a.label.localeCompare(b.label, undefined, { numeric: true }));

const capabilities = [...new Set(runs.flatMap((r) => Object.keys(r.results)))].sort();
const mark = { pass: '✅', fail: '❌' };

const lines = [
  '# Compatibility',
  '',
  'Generated by `scripts/compat-matrix.mjs` from contract tests against real Spree stores',
  '(`packages/spree-sdk/contract`). Do not edit by hand.',
  '',
  `| Capability | ${runs.map((r) => `Spree ${r.label}`).join(' | ')} |`,
  `| --- | ${runs.map(() => ':---:').join(' | ')} |`,
  `| API | ${runs.map((r) => `\`${r.family ?? '?'}\``).join(' | ')} |`,
  ...capabilities.map((c) => `| \`${c}\` | ${runs.map((r) => mark[r.results[c]] ?? '–').join(' | ')} |`),
  '',
  '✅ proven by contract tests · ❌ failing · – not tested yet',
  '',
];
writeFileSync('docs/compatibility.md', lines.join('\n'));
console.log(`Wrote docs/compatibility.md (${runs.length} versions, ${capabilities.length} capabilities)`);
